import {expect,test} from '@playwright/test';

test('Director, Guardian, Desk and Instructor share one child and consent record',async({page})=>{
 await page.setViewportSize({width:390,height:900});
 const switchTo=async(role)=>{await page.getByTestId('account-menu').click();await page.getByTestId('account-choice-'+role).click();};
 await page.goto('/?view=director');
 await page.getByTestId('director-nav-children').click();
 await page.getByTestId('director-add').click();
 await page.getByTestId('child-name').fill('New Demo Child');
 await page.getByTestId('child-guardian').selectOption({label:'Alyssa Chen'});
 await page.getByTestId('child-group').selectOption('spruce-3');
 await page.getByTestId('child-level').selectOption('Level 1');
 await page.getByTestId('child-emergency-name').fill('Alyssa Chen');
 await page.getByTestId('child-emergency-phone').fill('6045550101');
 await page.getByTestId('child-save').click();
 await expect(page.getByTestId('child-dialog')).not.toBeVisible();
 await switchTo('guardian');
 await expect(page.getByTestId('workspace-title')).toHaveText('Hello, Alyssa Chen');
 await expect(page.getByTestId('guardian')).not.toContainText('Noah Singh');
 const child=page.locator('.g-child-row').filter({hasText:'New Demo Child'});
 await expect(child).toBeVisible();
 await child.locator('[data-consent]').click();
 for(const [key,value] of Object.entries({emergencyRelationship:'Mother',medical:'None',medications:'None',allergies:'Peanuts',guardianSignature:'Alyssa Chen'})) await page.getByTestId('consent-'+key).fill(value);
 await page.locator('[data-tag-input]').fill('Alyssa Chen (Mother)');
 await page.locator('[data-tag-input]').press('Enter');
 await page.locator('[data-required-check]').nth(0).check();
 await page.locator('[data-required-check]').nth(1).check();
 await page.getByRole('button',{name:'Submit consent',exact:true}).click();
 await expect(child).toContainText('Consent on file');
 await switchTo('instructor');
 const instructorChild=page.getByTestId('roster-row').filter({hasText:'New Demo Child'});
 await expect(instructorChild).toContainText('Expected');
 await instructorChild.getByRole('button',{name:'View details'}).click();
 await expect(page.getByTestId('ops-detail')).toContainText('Peanuts');
 await page.getByTestId('ops-close').click();
 await switchTo('desk');
 const deskChild=page.getByTestId('roster-row').filter({hasText:'New Demo Child'});
 await expect(deskChild).toContainText('Expected');
 await expect(deskChild).not.toContainText('Consent needed');
 await deskChild.getByRole('button',{name:'View details'}).click();
 await expect(page.getByTestId('ops-detail')).toContainText('Guardian consent on file');
 await page.getByTestId('checkin-jacket').selectOption('blue');
 await page.getByTestId('checkin-helmet').selectOption('white');
 await page.getByTestId('checkin-save').click();
 await page.getByTestId('ops-close').click();
 await switchTo('instructor');
 await expect(instructorChild).toContainText('Checked in');
});
