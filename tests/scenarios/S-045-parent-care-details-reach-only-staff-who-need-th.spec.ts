// piezas-scenario: S-045 v=c4455b1b7efe
import {expect,test} from '@playwright/test';

test('S-045: a guardian completes consent and staff receive the care details they need',async({page})=>{
 await page.goto('/?view=director');
 await page.getByTestId('director-nav-children').click();
 await page.getByTestId('director-add').click();
 await page.getByTestId('child-name').fill('Care Access Demo');
 await page.getByTestId('child-guardian').selectOption({label:'Alyssa Chen'});
 await page.getByTestId('child-group').selectOption('spruce-3');
 await page.getByTestId('child-level').selectOption('Level 1');
 await page.getByTestId('child-emergency-name').fill('Alyssa Chen');
 await page.getByTestId('child-emergency-phone').fill('6045550199');
 await page.getByTestId('child-save').click();
 if(await page.getByTestId('child-profile').isVisible()) await page.getByTestId('dialog-close').click();
 await page.getByTestId('account-menu').click();
 await page.getByTestId('account-choice-guardian').click();
 await page.locator('.g-child-row').filter({hasText:'Care Access Demo'}).getByRole('button',{name:'Fill consent form'}).click();
 const form=page.getByRole('dialog');
 await expect(form).toContainText('Consent form');
 await expect(form.locator('input[readonly]').first()).toHaveValue('Care Access Demo');
 await form.getByTestId('consent-emergencyName').fill('Alyssa Chen');
 await form.getByTestId('consent-emergencyPhone').fill('6045550199');
 await form.getByTestId('consent-emergencyRelationship').selectOption('Mother');
 await form.getByTestId('consent-medical').fill('Asthma');
 await form.getByTestId('consent-medications').fill('Blue inhaler, in backpack');
 await form.getByTestId('consent-allergies').fill('None');
 await form.locator('[data-pickup-name]').fill('Alyssa Chen');
 await form.locator('[data-pickup-relationship]').selectOption('Mother');
 await form.locator('[data-pickup-add]').click();
 await form.getByTestId('consent-guardianSignature').fill('Alyssa Chen');
 await form.locator('[data-required-check]').nth(0).check();
 await form.locator('[data-required-check]').nth(1).check();
 await form.getByRole('button',{name:'Submit consent'}).click();
 await expect(page.locator('.g-child-row').filter({hasText:'Care Access Demo'})).toContainText('Consent on file');
 await page.getByTestId('account-menu').click();
 await page.getByTestId('account-choice-desk').click();
 await page.locator('[data-testid^="desk-child-card-"]').filter({hasText:'Care Access Demo'}).locator('.o-child').click();
 await expect(page.getByTestId('ops-detail')).toContainText('Asthma');
 await expect(page.getByTestId('ops-detail')).toContainText('Blue inhaler, in backpack');
 await page.getByTestId('ops-close').click();
 await page.locator('[data-testid^="desk-child-card-"]').filter({hasText:'Care Access Demo'}).getByRole('button',{name:'Check-in'}).click();
 await page.getByTestId('checkin-bib').fill('226');
 await page.getByTestId('checkin-jacket').selectOption('blue');
 await page.getByTestId('checkin-helmet').selectOption('black');
 await page.getByTestId('checkin-save').click();
 await page.getByTestId('account-menu').click();
 await page.getByTestId('account-choice-instructor').click();
 const instructorChild=page.getByTestId('roster-row').filter({hasText:'Care Access Demo'});
 await instructorChild.getByRole('button',{name:'View child'}).click();
 await expect(page.getByTestId('ops-detail')).toContainText('Asthma');
 await expect(page.getByTestId('ops-detail')).not.toContainText('604-555-0199');
 await expect(page.getByTestId('roster-row').filter({hasText:'Noah Singh'})).toHaveCount(0);
});
