import {expect,test} from '@playwright/test';

test('registration alone supports a lesson day across all five roles',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 const id='import-child-KM-2025-118204';
 const by=id=>page.getByTestId(id);
 const role=async name=>{
  await by('account-menu').click();
  await by('account-choice-'+name).click();
 };
 await page.goto('/prototype?view=director');
 await by('registration-import').click();
 await by('prototype-data').selectOption('registration');
 await by('load-demo-data').click();
 await by('registration-sample').click();
 await expect(by('registration-review')).toContainText(/300 new/);
 await by('registration-apply').click();
 await expect(by('director-today-count')).toHaveText('150');
 await expect(page.locator('.prototype-controls')).toHaveCount(0);
 await role('guardian');
 await page.locator('[data-consent="'+id+'"]').click();
 await by('consent-emergencyName').fill('Melissa Parr');
 await by('consent-emergencyPhone').fill('4165550142');
 await by('consent-emergencyRelationship').selectOption('Mother');
 await by('consent-medical').fill('Asthma');
 await by('consent-medications').fill('None');
 await by('consent-allergies').fill('None');
 await by('consent-pickupInput').fill('Melissa Parr');
 await by('consent-pickupRelationship').selectOption('Mother');
 await page.locator('[data-pickup-add]').click();
 await by('consent-confirmAccuracy').check();
 await by('consent-confirmSharing').check();
 await by('consent-guardianSignature').fill('Melissa Parr');
 await page.getByRole('button',{name:'Submit consent',exact:true}).click();
 await page.locator('.g-consent-dialog').waitFor({state:'hidden'});
 await role('director');
 await by('director-nav-children').click();
 await by('director-search').fill('Owen Parr');
 await by('child-open-'+id).click();
 await by('profile-edit-'+id).click();
 await expect(by('child-emergency-phone')).toHaveValue('+1 416 555 0142');
 await expect(by('child-emergency-relationship')).toHaveValue('Mother');
 await expect(by('pickup-0-relationship')).toHaveValue('Mother');
 await by('child-group').selectOption('spruce-3');
 await by('child-save').click();
 await by('dialog-close').click();
 await role('desk');
 await by('roster-search').fill('Owen Parr');
 await by('desk-action-'+id).click();
 await by('checkin-bib').fill('482');
 await expect(by('checkin-bib-label')).toContainText(/3-482/);
 await by('checkin-jacket').selectOption('green');
 await by('checkin-helmet').selectOption('white');
 await by('checkin-save').click();
 await expect(by('desk-child-card-'+id)).toContainText(/3-482/);
 await role('instructor');
 await expect(by('roster-row')).toContainText(/3-482/);
 await by('instructor-report-missing').click();
 await by('radio-child').selectOption(id);
 await by('radio-place').fill('Meeting flag');
 await by('radio-save').click();
 await expect(by('radio-alert-status')).toContainText(/Report saved/);
 await by('ops-close').click();
 await role('patrol');
 const dossier=by('patrol-alert').filter({hasText:'Owen Parr'});
 await dossier.waitFor();
 await expect(dossier).toContainText(/3-482/);
 await expect(dossier).toContainText(/import-child-KM-2025-118204/);
 await expect(dossier).toContainText(/Medical conditions: Asthma/);
 await expect(dossier).toContainText(/Melissa Parr/);
 await dossier.getByTestId('patrol-request-lift-scan').click();
 await expect(dossier.getByTestId('patrol-action-message')).toContainText(/No lift scan request was sent/);
 await dossier.getByTestId('patrol-log-found-mobile').click();
 await dossier.locator('[data-found-confirm]').click();
 await dossier.waitFor({state:'hidden'});
 await role('instructor');
 await expect(by('instructor-found-'+id)).toHaveCount(0);
 await role('desk');
 await by('roster-search').fill('Owen Parr');
 await by('desk-action-'+id).click();
 await by('pickup-adult').selectOption('0');
 await by('pickup-staff').fill('Desk Demo');
 await by('pickup-verified').check();
 await by('pickup-bib-return').selectOption('returned');
 await by('pickup-save').click();
 await expect(by('ops-detail')).toContainText(/Released to Melissa Parr/);
 await expect(by('bib-return-status')).toContainText(/Bib returned/);
 await page.goto('/prototype?view=director&data=imports');
 await expect(by('director-today-count')).toContainText(/^150$/);
 await by('director-nav-children').click();
 await by('director-search').fill('Owen Parr');
 await by('child-open-'+id).click();
 await expect(by('profile-details')).toContainText(/Consent needed/);
});
